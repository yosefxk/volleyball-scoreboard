package com.volleyball.scoreboard

import android.content.ContentValues
import android.content.Context
import android.content.Intent
import android.os.Build
import android.os.Environment
import android.provider.MediaStore
import android.util.Log
import androidx.core.content.FileProvider
import java.io.File
import java.io.FileOutputStream
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale
import java.util.concurrent.Executors

object ScoreboardLogger {

    private const val TAG = "ScoreboardLogger"
    const val FILE_NAME = "volleyball-scoreboard.log"
    private val executor = Executors.newSingleThreadExecutor()
    private val dateFormat = SimpleDateFormat("yyyy-MM-dd HH:mm:ss.SSS", Locale.US)

    /**
     * High-frequency logger:
     * Appends solely to the app's private external storage file (localFile).
     * Does NOT touch MediaStore here to prevent generating duplicate files.
     */
    fun log(context: Context, tag: String, message: String) {
        val timestamp = synchronized(dateFormat) { dateFormat.format(Date()) }
        val line = "[$timestamp] [$tag] $message\n"
        Log.i("VBScoreboard", line.trimEnd())

        val appContext = context.applicationContext
        executor.execute {
            try {
                val localFile = File(appContext.getExternalFilesDir(null), FILE_NAME)
                FileOutputStream(localFile, true).use { fos ->
                    fos.write(line.toByteArray(Charsets.UTF_8))
                    fos.flush()
                }
            } catch (e: Exception) {
                Log.e(TAG, "Failed writing log line", e)
            }
        }
    }

    /**
     * Synchronizes the single complete log file to the public Downloads folder.
     * Automatically cleans up any existing duplicate files (e.g. volleyball-scoreboard (1).log)
     * previously generated by MediaStore, leaving exactly one clean file.
     */
    fun syncToDownloads(context: Context) {
        val appContext = context.applicationContext
        executor.execute {
            try {
                val localFile = File(appContext.getExternalFilesDir(null), FILE_NAME)
                if (!localFile.exists() || localFile.length() == 0L) {
                    return@execute
                }

                if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.Q) {
                    val resolver = appContext.contentResolver

                    // 1. Delete all previous volleyball-scoreboard*.log files created by this app in Downloads
                    try {
                        val selection = "${MediaStore.MediaColumns.DISPLAY_NAME} LIKE ?"
                        val selectionArgs = arrayOf("volleyball-scoreboard%")
                        val deleted = resolver.delete(
                            MediaStore.Downloads.EXTERNAL_CONTENT_URI,
                            selection,
                            selectionArgs
                        )
                        if (deleted > 0) {
                            Log.i(TAG, "Cleaned up $deleted duplicate log file(s) from Downloads")
                        }
                    } catch (e: Exception) {
                        Log.w(TAG, "Failed cleaning duplicate downloads", e)
                    }

                    // 2. Insert single clean file with IS_PENDING = 1
                    val values = ContentValues().apply {
                        put(MediaStore.MediaColumns.DISPLAY_NAME, FILE_NAME)
                        put(MediaStore.MediaColumns.MIME_TYPE, "text/plain")
                        put(MediaStore.MediaColumns.RELATIVE_PATH, Environment.DIRECTORY_DOWNLOADS)
                        put(MediaStore.MediaColumns.IS_PENDING, 1)
                    }

                    val uri = resolver.insert(MediaStore.Downloads.EXTERNAL_CONTENT_URI, values)
                    if (uri != null) {
                        resolver.openOutputStream(uri, "rwt")?.use { os ->
                            localFile.inputStream().use { input ->
                                input.copyTo(os)
                            }
                            os.flush()
                        }

                        // 3. Publish file by clearing IS_PENDING
                        values.clear()
                        values.put(MediaStore.MediaColumns.IS_PENDING, 0)
                        resolver.update(uri, values, null, null)
                        Log.i(TAG, "Synced volleyball-scoreboard.log to Downloads successfully")
                    }
                } else {
                    @Suppress("DEPRECATION")
                    val downloadsDir = Environment.getExternalStoragePublicDirectory(Environment.DIRECTORY_DOWNLOADS)
                    downloadsDir.mkdirs()

                    // Remove legacy duplicates
                    try {
                        downloadsDir.listFiles { f ->
                            f.name.startsWith("volleyball-scoreboard") && f.name.endsWith(".log")
                        }?.forEach { it.delete() }
                    } catch (e: Exception) {
                        Log.w(TAG, "Failed cleaning legacy downloads", e)
                    }

                    val destFile = File(downloadsDir, FILE_NAME)
                    localFile.copyTo(destFile, overwrite = true)
                }
            } catch (e: Exception) {
                Log.e(TAG, "Failed syncing to Downloads folder", e)
            }
        }
    }

    fun shareLog(context: Context) {
        syncToDownloads(context)
        try {
            val localFile = File(context.getExternalFilesDir(null), FILE_NAME)
            if (!localFile.exists()) {
                log(context, "INFO", "Log file initialized.")
            }
            val uri = FileProvider.getUriForFile(context, "${context.packageName}.fileprovider", localFile)
            val intent = Intent(Intent.ACTION_SEND).apply {
                type = "text/plain"
                putExtra(Intent.EXTRA_STREAM, uri)
                putExtra(Intent.EXTRA_SUBJECT, "Volleyball Scoreboard Log")
                addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
                addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
            }
            val chooser = Intent.createChooser(intent, "Share Volleyball Scoreboard Log").apply {
                addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
            }
            context.startActivity(chooser)
        } catch (e: Exception) {
            Log.e(TAG, "Failed to share log", e)
        }
    }

    fun openLog(context: Context) {
        syncToDownloads(context)
        try {
            val localFile = File(context.getExternalFilesDir(null), FILE_NAME)
            if (!localFile.exists()) {
                log(context, "INFO", "Log file initialized.")
            }
            val uri = FileProvider.getUriForFile(context, "${context.packageName}.fileprovider", localFile)
            val intent = Intent(Intent.ACTION_VIEW).apply {
                setDataAndType(uri, "text/plain")
                addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
                addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
            }
            context.startActivity(intent)
        } catch (e: Exception) {
            shareLog(context)
        }
    }
}
